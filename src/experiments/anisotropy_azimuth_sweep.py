def main():
    run_dir = make_run_dir(EXPERIMENT_NAME)
    output_files = []
    all_exp_rows = []
    all_true_range_rows = []
    nscore_corrections_by_combo = {}
    n_samples_actual_by_combo = {}

    t_start = time.time()

    print("Analytic true-range-by-azimuth table (3 ratios x 36 azimuths)...")
    for ratio_label in RATIO_ORDER:
        info = RATIO_LEVELS[ratio_label]
        all_true_range_rows.extend(
            true_range_rows(ratio_label, info["hmaj1"], info["hmin1"])
        )

    print(
        f"Truth realizations, sample draws, and azimuth-scan experimental "
        f"variograms (3 ratios x {len(TRUTH_SEEDS_SWEEP)} truth_seeds x "
        f"{len(SAMPLE_SEED_DRAWS_SWEEP)} draws x {len(AZIMUTHS_DEG)} azimuths)..."
    )
    for ratio_label in RATIO_ORDER:
        info = RATIO_LEVELS[ratio_label]
        hmaj1, hmin1, fname_label = info["hmaj1"], info["hmin1"], info["filename_label"]
        for truth_seed in TRUTH_SEEDS_SWEEP:
            truth = get_base_case_truth(
                truth_seed=truth_seed, hmaj1=hmaj1, hmin1=hmin1, nug=NUG_ANISO
            )
            truth_fname = f"truth_{fname_label}_seed{truth_seed}.npy"
            np.save(run_dir / truth_fname, truth)
            output_files.append(truth_fname)

            for draw_label, draw_seed in zip(DRAW_LABELS_SWEEP, SAMPLE_SEED_DRAWS_SWEEP):
                samples = get_conditioning_samples(
                    truth, sample_seed=draw_seed, n_samples=N_SAMPLES_SWEEP
                )
                ns, _vr, _vrg, corrections = nscore_corrected(samples, VCOL, verbose=False)
                samples = samples.copy()
                samples[NSCOL] = ns

                combo_key = f"{ratio_label}|truth_seed={truth_seed}|{draw_label}"
                nscore_corrections_by_combo[combo_key] = corrections
                n_samples_actual_by_combo[combo_key] = int(len(samples))

                samples_fname = f"samples_{fname_label}_seed{truth_seed}_{draw_label}.csv"
                samples.to_csv(run_dir / samples_fname, index=False)
                output_files.append(samples_fname)

                all_exp_rows.extend(
                    experimental_variogram_rows_sweep(
                        samples, ratio_label, hmaj1, hmin1, truth_seed, draw_seed
                    )
                )

        print(f"  ratio {ratio_label} (hmaj1={hmaj1:g}, hmin1={hmin1:g}) done")

    elapsed = time.time() - t_start

    exp_df = pd.DataFrame(all_exp_rows)[COMPARISON_COLUMNS]
    true_range_df = pd.DataFrame(all_true_range_rows)[TRUE_RANGE_COLUMNS]

    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    exp_path = PROCESSED_DIR / "experimental_variogram.csv"
    true_range_path = PROCESSED_DIR / "true_range_by_azimuth.csv"
    exp_df.to_csv(exp_path, index=False)
    true_range_df.to_csv(true_range_path, index=False)

    actual_counts = sorted(set(n_samples_actual_by_combo.values()))
    print(
        f"n_samples_requested={N_SAMPLES_SWEEP} ('{DENSITY_LABEL}' density level); "
        f"n_samples_actual observed across all {len(n_samples_actual_by_combo)} combos: "
        f"{actual_counts} (duplicate-cell removal in random_interior_samples can make "
        "this < requested)"
    )

    manifest_path = save_result(
        experiment=EXPERIMENT_NAME,
        params=build_params(nscore_corrections_by_combo, n_samples_actual_by_combo),
        seed_or_seeds=sorted(_NEW_SEEDS),
        run_dir=run_dir,
        code_entrypoint=CODE_ENTRYPOINT,
        output_files=output_files,
    )

    print(f"\nRun directory: {run_dir}")
    print(f"Manifest: {manifest_path}")
    print(f"experimental_variogram.csv: {exp_path} ({len(exp_df)} rows)")
