def true_practical_range_at_azimuth(
    azimuth_deg: float, hmaj1: float, hmin1: float, azi1: float = AZI1_ANISO
) -> float:
    """Analytic TRUE practical range of this project's spherical, geometric-
    anisotropy variogram model, at azimuth ``azimuth_deg`` (GSLIB compass-
    bearing convention, same as ``azi1``/``gamv``'s own ``azm`` argument).

    Closed-form solution of ``geostats.setup_rotmat``/``geostats.cova2``'s own
    rotation + anisotropy-scaling transform -- see module docstring
    "Analytic TRUE practical range per azimuth" for the full derivation and
    its numeric verification against ``geostats.vmodel``. Reduces to exactly
    ``hmaj1`` at ``azimuth_deg == azi1`` and exactly ``hmin1`` at
    ``azimuth_deg == azi1 + 90`` (mod 180).

    This is the "answer key" value -- callers must keep it in a file/column
    separate from anything shown to a human making an azimuth/range call from
    the experimental variogram alone (see module docstring).
    """
    delta_rad = math.radians(azimuth_deg - azi1)
    ratio = hmaj1 / hmin1
    denom = math.sqrt(math.cos(delta_rad) ** 2 + (ratio**2) * math.sin(delta_rad) ** 2)
    return hmaj1 / denom


def true_range_rows(ratio_label: str, hmaj1: float, hmin1: float) -> list:
    """One row per azimuth in AZIMUTHS_DEG for this (ratio_label, hmaj1,
    hmin1) -- independent of truth_seed/sample_draw_seed. Callers must not
    call this once per (truth_seed, draw)."""
    rows = []
    for azimuth_deg in AZIMUTHS_DEG:
        rows.append(
            {
                "ratio_label": ratio_label,
                "hmaj1": hmaj1,
                "hmin1": hmin1,
                "azimuth_deg": float(azimuth_deg),
                "true_practical_range": true_practical_range_at_azimuth(
                    azimuth_deg, hmaj1, hmin1
                ),
            }
        )
    return rows


def experimental_variogram_rows_sweep(
    samples_ns: pd.DataFrame,
    ratio_label: str,
    hmaj1: float,
    hmin1: float,
    truth_seed: int,
    draw_seed: int,
) -> list:
    """gamv-computed experimental variogram for one (ratio, truth_seed,
    draw), at every azimuth in AZIMUTHS_DEG. ``samples_ns`` must already
    carry the normal-scored column NSCOL (see module docstring -- gamv is
    never called on raw physical porosity here, same rule as
    anisotropy_variogram_check.py)."""
    rows = []
    for azimuth_deg in AZIMUTHS_DEG:
        dis, gamma, npair = geostats.gamv(
            samples_ns,
            "X",
            "Y",
            NSCOL,
            GAMV_TMIN,
            GAMV_TMAX,
            GAMV_LAG_DIST,
            GAMV_LAG_TOL,
            GAMV_NLAG,
            float(azimuth_deg),
            GAMV_ATOL_SWEEP,
            GAMV_BANDH,
            GAMV_ISILL,
        )
        # Drop index 0 (degenerate zero-separation "self pair" bin) and the
        # trailing index (GAMV_NLAG + 1, structurally never filled) -- same
        # gamv bin-indexing subtlety documented in
        # anisotropy_variogram_check.py's module docstring.
        for lag_h, gamma_v, n_v in zip(dis[1:-1], gamma[1:-1], npair[1:-1]):
            rows.append(
                {
                    "ratio_label": ratio_label,
                    "hmaj1": hmaj1,
                    "hmin1": hmin1,
                    "truth_seed": truth_seed,
                    "sample_draw_seed": draw_seed,
                    "azimuth_deg": float(azimuth_deg),
                    "lag": float(lag_h),
                    "gamma": float(gamma_v),
                    "npair": float(n_v),
                }
            )
    return rows


