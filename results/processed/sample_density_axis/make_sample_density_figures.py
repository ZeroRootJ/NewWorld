"""Build the sample-density-axis figures (docs/progress.md "axis 5 -- sample
count/sparsity"), over the 3 axis levels labelled 5% / 2% / 1% of the
2500-cell grid (n_samples REQUESTED = 125 / 50 / 25).

REQUESTED vs. ACTUAL sample counts
----------------------------------
``random_interior_samples`` drops duplicate cell mappings, so the requested
count is not always what was used: the "5" level actually conditions on 121
samples = 4.84% of the grid, not 125 = 5%. ("2" and "1" happen to lose no
draws: 50 = 2.00% and 25 = 1.00%.) Every number printed on a figure --
x-axis tick labels, panel titles, captions -- is therefore taken from the
ACTUAL counts recorded in sample_overlap.json, never from SAMPLE_COUNTS.
The string "5"/"2"/"1" survives only as the axis-level IDENTIFIER used to
join against metrics.csv's ``axis_level`` column.

Generalized from results/processed/range_axis/make_range_axis_figures.py --
the panel layout, shared-colorbar handling and metric-panel definitions are
reused, not reinvented.

(a) MAIN FIGURE -- a 4-panel metric-vs-sample-fraction plot (MSE / UMG /
    summed predictive variance / mean predictive variance), one line per
    method, x axis on a log scale and REVERSED (5% -> 1%, i.e. dense ->
    sparse left to right).

    PARKED PANELS (user decision, 2026-09-15): the sharpness-family metrics
    (mean interval width, CRPS, 95% interval width) were taken out of the
    sample-density-axis workflow and replaced in the main figure by
    variance_sum / variance_mean. Consequently:
      - the former width/CRPS panels are gone from
        metrics_vs_sample_density.png, and
      - interval_width_p95_vs_sample_density.png IS NO LONGER GENERATED by
        this script. The previously generated file is intentionally left in
        results/figures/sample_density_axis/ (not deleted) and is now STALE
        with respect to metrics.csv, which no longer carries those metrics.
        The values behind it are preserved in
        results/processed/sample_density_axis/metrics_parked_sharpness.csv.
        To bring the panels back: set EMIT_SHARPNESS_METRICS = True in
        src/experiments/evaluate_sample_density_axis.py, re-run it, and
        re-add the panels here.
(b) Calibration (accuracy-plot) curves for all 3 levels in one 1x3 grid.
(c) ONE truth figure (3 panels) + per-level "truth & predictions" QC figures
    for the 4 methods.

Why only ONE truth figure: all three levels share TRUTH_SEED=101 AND the
base-case 300 m range, so the ground-truth field is LITERALLY IDENTICAL at
every level -- only the conditioning samples differ. Rendering it three times
would be pure duplication, so it is drawn once as a 1x3 panel of the same
field with each level's sample locations overlaid.

COLOR-SCALE CONVENTION (stated here and in every figure's caption):
  - POROSITY panels use ONE SHARED SCALE ACROSS ALL THREE LEVELS. This is
    possible on this axis precisely because the truth field is identical at
    every level (unlike the range axis, where each level had its own truth
    realization and only a within-level scale was defensible). Porosity
    panels from different levels here ARE directly comparable by color.
  - VARIANCE panels keep the range axis's WITHIN-LEVEL rule: one scale per
    level, anchored on that level's SGS/RBF/GP-MLE variance maxima (kriging's
    physical-unit Monte Carlo variance is annotated if it exceeds it).
    Predictive variance grows strongly as samples are removed, so a single
    global variance scale would flatten the 5% level into near-uniform color.
    CONSEQUENCE: variance panels are NOT comparable by color across levels --
    each variance panel is therefore annotated with its own numeric scale max
    so cross-level comparison remains possible from the numbers.

AXIS LIMITATION carried into the captions (see
src/experiments/sample_density_axis.py): the levels' sample LOCATIONS are
neither nested subsets NOR independent draws. Each level calls
``random_interior_samples`` with its own n at one shared seed, which draws
all X values first and then all Y values from a single RandomState, so the
levels SHARE their X draws and differ only in Y. Measured: all 20 distinct X
coordinates of the n=25 set also occur in the n=121 set and in the n=50 set
(20 of 20), while only 16 of its 18 distinct Y coordinates occur in the
n=121 set -- yet only 4 of 25 complete (X,Y) cells are shared with the n=121
set, 4 of 50 between n=50 and n=121, and 0 between n=25 and n=50. With one
realization per level, a level-to-level difference mixes "less data was
given" with "the data landed in different places" (chiefly along Y).

TAIL-ASSUMPTION CAVEAT (applied to the now-parked interval-width figure; kept
here because it still describes the preserved values in
metrics_parked_sharpness.csv): kriging's intervals are
back-transformed from normal-score space through a linear tail
extrapolation bounded by BACKTR_ZMIN/ZMAX, so ITS width -- and only its --
depends on that bound. At the sparsest level the kriging 95% width moves
from 8.64 (bound +-2 sigma) through 9.84 (the production +-4 sigma) to 11.03
(+-6 sigma), which is three different rank positions against SGS (9.26) and
GP-MLE (10.33). CRPS is robust to the same change (kriging 1.424 / 1.430 /
1.440 vs. GP-MLE 1.558), so the caveat is printed on the width figure only.
Numbers from results/processed/sample_density_axis/
kriging_backtransform_tail_sensitivity.csv (written by
src/experiments/diagnose_sample_density_axis.py).

Run dirs are read from
results/processed/sample_density_axis/source_runs.json.

Run with:
.venv/Scripts/python.exe -m results.processed.sample_density_axis.make_sample_density_figures
"""

