def _style_density_axis(ax):
    """Shared x-axis styling: log scale, reversed (dense -> sparse). Ticks are
    placed and labelled with ACTUAL sampled fractions/counts."""
    ax.set_xscale("log")
    ax.set_xlim(max(AXIS_LEVEL_FLOATS) * 1.35, min(AXIS_LEVEL_FLOATS) / 1.35)
    ax.set_xticks(AXIS_LEVEL_FLOATS)
    ax.set_xticklabels(
        [
            f"{PCT_ACTUAL[lvl]:.2f}%\n(n={N_SAMPLES_ACTUAL[lvl]})"
            for lvl in ALL_AXIS_LEVELS
        ]
    )
    ax.minorticks_off()
    ax.set_xlabel("Conditioning sample fraction of the 2500-cell grid (log scale, dense -> sparse)")


