P1_LAG_MAX_M = 850.0          # lag range of the experimental variogram (must cover range 800 m - half a bin)
P1_JITTER_FRAC = 0.18         # +- fraction of the level spacing (panels A, C), deterministic
P1_MARKER_S = 7.0


def _p1_rows(mt):
    from src.evaluation import conditioning_cell_mask
    from src.experiments.base_case import NUG, POR_MEAN, POR_STDEV, XMN, XSIZ, YMN, YSIZ
    from src.experiments.base_case_conditioning import (VCOL, build_vario, get_base_case_truth,
                                                        get_conditioning_samples)
    from src.experiments.base_case import NX, NY
    from src.experiments.evaluate_multi_truth_axes import MAP_MATCH_TOL, SAMPLES_MATCH_ATOL, _gaussian_metrics, \
        kriging_metrics
    from src.truth_model import make_porosity_truth_with_sim_ns
    import geostatspy.GSLIB as GSLIB
    from results.processed.sample_density_axis.make_length_and_variogram_figures import (
        LAG_BIN_WIDTH_M, MIN_PAIRS_PER_BIN, N_PAIRS_DRAWN, VARIOGRAM_PAIR_SEED, compute_experimental_variogram,
        spherical_semivariance)

    er = mt["exp"]["range"]
    cells = er["cells"].copy()
    met = read_metrics_csv(MTA_METRICS)
    umg_k = _per_cell(met, er["experiment"], "kriging", "umg")
    umg_s = _per_cell(met, er["experiment"], "sgs", "umg")
    rows = []
    checked_bitwise = False
    for c in cells.sort_values(["hmaj1", "truth_seed"]).itertuples():
        if c.hmaj1 != c.hmin1:
            raise ValueError(f"P1: E2 cell {c.config_key} not isotropic")
        if not np.isclose(c.nug, NUG, rtol=0, atol=1e-12):
            raise ValueError(f"P1: E2 cell {c.config_key} nugget {c.nug} != NUG {NUG}; model curve invalid")
        vario = build_vario(hmaj1=c.hmaj1, hmin1=c.hmin1, nug=c.nug)
        sill_ns = float(vario["nug"] + vario["cc1"])
        sill_phys = sill_ns * POR_STDEV ** 2
        with contextlib.redirect_stdout(io.StringIO()):
            truth, sim_ns = make_porosity_truth_with_sim_ns(NX, NY, XSIZ, YSIZ, XMN, YMN, vario, POR_MEAN, POR_STDEV,
                                                            int(c.truth_seed))
            if not checked_bitwise:   # one cell: identical to the evaluator's own generator call
                ref = get_base_case_truth(truth_seed=int(c.truth_seed), hmaj1=c.hmaj1, hmin1=c.hmin1, nug=c.nug)
                if not np.array_equal(ref, truth):
                    raise ValueError("P1: make_porosity_truth_with_sim_ns != get_base_case_truth")
                checked_bitwise = c.config_key
        if not np.array_equal(GSLIB.affine(sim_ns, POR_MEAN, POR_STDEV), truth):
            raise ValueError(f"P1 {c.config_key}: truth != affine(sim_ns)")
        # stored truth data: the conditioning samples (X, Y, value) recorded by the kriging and SGS runs
        samples_df = get_conditioning_samples(truth, sample_seed=int(c.sample_seed),
                                              n_samples=int(c.n_samples_requested))
        mask = conditioning_cell_mask(samples_df, NX, NY, XMN, YMN, XSIZ, YSIZ)
        kdir = _REPO_ROOT / c.run_dir_kriging_b
        sdir = _REPO_ROOT / c.run_dir_sgs_b1
        for d in (kdir, sdir):
            rec = pd.read_csv(d / "samples.csv")
            if len(rec) != len(samples_df) or not np.allclose(rec[["X", "Y", VCOL]].values,
                                                              samples_df[["X", "Y", VCOL]].values,
                                                              rtol=0, atol=SAMPLES_MATCH_ATOL):
                raise ValueError(f"P1: {d}/samples.csv != regenerated truth samples")
        key = (c.axis_level, c.truth_seed, c.sample_rep)
        km = kriging_metrics(kdir, truth[mask], mask)
        ens = np.load(sdir / "sgs_realizations.npy")
        smean, svar = ens.mean(axis=0), ens.var(axis=0, ddof=1)
        if not (np.allclose(smean, np.load(sdir / "sgs_mean_map.npy"), rtol=MAP_MATCH_TOL, atol=MAP_MATCH_TOL)
                and np.allclose(svar, np.load(sdir / "sgs_var_map.npy"), rtol=MAP_MATCH_TOL, atol=MAP_MATCH_TOL)):
            raise ValueError(f"P1: {sdir} recomputed ensemble maps differ from saved maps")
        sm = _gaussian_metrics(truth[mask], smean[mask], smean[mask], svar[mask], f"P1 sgs {c.config_key}")
        for name, got, saved in (("kriging", km["umg"], umg_k.loc[key]), ("sgs", sm["umg"], umg_s.loc[key])):
            if not np.isclose(got, saved, rtol=1e-12, atol=1e-12):
                raise ValueError(f"P1 {c.config_key}: recomputed {name} umg {got} != metrics.csv {saved}")
        with contextlib.redirect_stdout(io.StringIO()):
            v = compute_experimental_variogram(truth, lag_max_m=P1_LAG_MAX_M, range_m=c.hmaj1)
        lo, hi = c.hmaj1 - LAG_BIN_WIDTH_M / 2.0, c.hmaj1 + LAG_BIN_WIDTH_M / 2.0
        centers = v["lag_bin_center_m"].values
        gam = {}
        for tag, lag in (("lo", lo), ("hi", hi)):
            b = np.where(np.isclose(centers, lag, rtol=0, atol=1e-9))[0]
            if len(b) != 1:
                raise ValueError(f"P1 {c.config_key}: no lag bin centred at {lag} m")
            if int(v["n_pairs"].values[b[0]]) < MIN_PAIRS_PER_BIN:
                raise ValueError(f"P1 {c.config_key}: bin {lag} m has < {MIN_PAIRS_PER_BIN} pairs")
            gam[tag] = (float(v["semivariance_empirical"].values[b[0]]),
                        float(spherical_semivariance(lag, range_m=c.hmaj1)), int(v["n_pairs"].values[b[0]]))
        rows.append({
            "range_m": float(c.hmaj1), "truth_seed": int(c.truth_seed), "sample_rep": c.sample_rep,
            "axis_level": c.axis_level, "n": int(len(samples_df)),
            "sill_ns": sill_ns, "sill_phys": sill_phys,
            "var_phys0": float(np.var(truth)), "var_phys1": float(np.var(truth, ddof=1)),
            "var_ns0": float(np.var(sim_ns)), "mean_ns": float(np.mean(sim_ns)),
            "ratio_ns": float(np.var(sim_ns)) / sill_ns, "ratio_phys": float(np.var(truth)) / sill_phys,
            "gam_lo": gam["lo"][0], "model_lo": gam["lo"][1], "np_lo": gam["lo"][2],
            "gam_hi": gam["hi"][0], "model_hi": gam["hi"][1], "np_hi": gam["hi"][2],
            "umg_kriging": float(umg_k.loc[key]), "umg_sgs": float(umg_s.loc[key]),
        })
    df = pd.DataFrame(rows)
    df["gam_ratio_lo"] = df["gam_lo"] / df["model_lo"]
    df["gam_ratio_hi"] = df["gam_hi"] / df["model_hi"]
    consts = {"LAG_BIN_WIDTH_M": LAG_BIN_WIDTH_M, "N_PAIRS_DRAWN": N_PAIRS_DRAWN,
              "VARIOGRAM_PAIR_SEED": VARIOGRAM_PAIR_SEED, "MIN_PAIRS_PER_BIN": MIN_PAIRS_PER_BIN,
              "POR_STDEV": POR_STDEV, "POR_MEAN": POR_MEAN, "NUG": NUG, "checked_bitwise": checked_bitwise}
    return df, consts


def _jitter(n, step, frac):
    return (np.linspace(-1.0, 1.0, n) if n > 1 else np.zeros(1)) * frac * step


def compute_p1(mt):
    stem = "P1_range_truth_realization_stats"
    df, k = _p1_rows(mt)
    er = mt["exp"]["range"]
    levels = sorted(df["range_m"].unique())
    if len(levels) != er["n_levels"] or set(df.groupby("range_m").size()) != {er["n_cells"]}:
        raise ValueError("P1: unexpected E2 level / cell counts")
    sill_phys = sorted(df["sill_phys"].unique())
    sill_ns = sorted(df["sill_ns"].unique())
    if len(sill_phys) != 1 or len(sill_ns) != 1:
        raise ValueError(f"P1: more than one model sill {sill_phys}")
    sill_phys, sill_ns = sill_phys[0], sill_ns[0]
    phys_dev = float(np.max(np.abs(df["ratio_phys"] - 1.0)))
    bw = k["LAG_BIN_WIDTH_M"]

    note = (
        f"E2 (range axis), {er['n_truth']} ground-truth realizations per range level × {len(levels)} levels, nugget "
        f"{k['NUG']:g}, model sill {sill_ns:g} (standard-normal) = {sill_phys:g} porosity %². Every truth map was "
        f"regenerated with the experiment's generator and checked against the stored samples and metrics. The "
        f"porosity map is the standard-normal simulation after an affine rescaling to exactly mean {k['POR_MEAN']:g} "
        f"and variance {k['POR_STDEV'] ** 2:g} (ddof = 0), so its variance / sill is 1 for every map (max |ratio − 1| "
        f"= {phys_dev:.1e}); A and B therefore use the variance of the standard-normal simulation BEFORE rescaling "
        f"(÷ unit sill). C: experimental variogram of the porosity map ({k['N_PAIRS_DRAWN']:,} random pairs, "
        f"{bw:g} m bins) in the bin centred at range − {bw / 2:g} m, ÷ true spherical model at that lag. Points = "
        f"individual realizations (spread horizontally), bars = level mean."
    )
    def tbl(col, fmt):
        g = df.groupby("range_m")[col]
        return "; ".join(f"{lvl:g} m: mean {g.mean()[lvl]:{fmt}}, min {g.min()[lvl]:{fmt}}, max {g.max()[lvl]:{fmt}}"
                         for lvl in levels)

    per_cell = [
        f"  {r.range_m:g} m truth {r.truth_seed}: var_ns(ddof0) {r.var_ns0:.4f} (mean_ns {r.mean_ns:+.4f}), "
        f"var_phys ddof0 {r.var_phys0:.6f} / ddof1 {r.var_phys1:.6f}, gamma[{r.range_m - bw / 2:g} m] {r.gam_lo:.3f} "
        f"(model {r.model_lo:.3f}, ratio {r.gam_ratio_lo:.3f}, {r.np_lo} pairs), gamma[{r.range_m + bw / 2:g} m] "
        f"{r.gam_hi:.3f} (model {r.model_hi:.3f}, ratio {r.gam_ratio_hi:.3f}, {r.np_hi} pairs), UMG kriging "
        f"{r.umg_kriging:.4f}, UMG SGS {r.umg_sgs:.4f}"
        for r in df.sort_values(["range_m", "truth_seed"]).itertuples()]
    from scipy.stats import spearmanr
    rho_k = spearmanr(df["ratio_ns"], df["umg_kriging"])
    rho_s = spearmanr(df["ratio_ns"], df["umg_sgs"])
    lines = _status(
        stem,
        inputs=[
            f"{_rel(MTA_CELLS)} (E2 cells: truth_seed, sample_seed, n_samples_requested, run_dir_kriging_b, "
            "run_dir_sgs_b1, config_key)",
            f"{_rel(mt['src_dir'])}/run_config.json (hmaj1 / hmin1 / nug per cell, via _load_multi_truth)",
            f"{_rel(MTA_METRICS)} (E2 kriging and sgs umg per cell; recomputed here from the run dirs with "
            "evaluate_multi_truth_axes.kriging_metrics / _gaussian_metrics and asserted equal, rtol 1e-12)",
            "E2 kriging run dirs (samples.csv, kriging maps, nscore_transform_table.csv) and SGS batch-1 run dirs "
            "(samples.csv, sgs_realizations.npy, sgs_mean_map.npy, sgs_var_map.npy), as listed in evaluation_cells.csv",
            "truth maps regenerated with src/truth_model.make_porosity_truth_with_sim_ns(build_vario(hmaj1, hmin1, "
            "nug), POR_MEAN, POR_STDEV, truth_seed) (the sgsim call site of get_base_case_truth); checks: "
            f"bit-identical to get_base_case_truth for cell {k['checked_bitwise']}; truth == GSLIB.affine(sim_ns) for "
            "every cell; regenerated conditioning samples (X, Y, value) == samples.csv of the kriging AND SGS run of "
            f"every cell (atol 1e-10); recomputed kriging / SGS UMG == metrics.csv for all {len(df)} cells",
            "experimental variogram: results/processed/sample_density_axis/make_length_and_variogram_figures."
            f"compute_experimental_variogram(truth, lag_max_m={P1_LAG_MAX_M:g}, range_m=true range) and "
            "spherical_semivariance(h, range_m=true range) (reused, not reimplemented)",
        ],
        panels=[
            ("A", "variance (ddof=0, all 2500 cells) of the standard-normal simulation sim_ns before the affine "
                  f"rescaling ÷ model sill nug + cc1 = {sill_ns:g}, vs true range; per level: " + tbl("ratio_ns", ".4f")),
            ("B", f"per-cell oracle simple-kriging UMG (E2) vs the panel-A ratio, colour = range level. Spearman rho "
                  f"(all {len(df)} cells): kriging {rho_k.correlation:.3f} (p {rho_k.pvalue:.2g}); same with SGS UMG "
                  f"(not drawn): {rho_s.correlation:.3f} (p {rho_s.pvalue:.2g})"),
            ("C", f"experimental semivariance of the porosity map in the bin centred at range − {bw / 2:g} m ÷ "
                  "spherical model at that lag; per level: " + tbl("gam_ratio_lo", ".3f")
                  + f". Same at range + {bw / 2:g} m (not drawn): " + tbl("gam_ratio_hi", ".3f")),
            ("UMG per level (mean)", "; ".join(
                f"{lvl:g} m kriging {df.loc[df.range_m == lvl, 'umg_kriging'].mean():.4f}, SGS "
                f"{df.loc[df.range_m == lvl, 'umg_sgs'].mean():.4f}" for lvl in levels)),
        ],
        in_figure_note="DATA STATUS: " + note,
        limits=[
            f"model sill from build_vario(...): nug + cc1 = {sill_ns:g} in standard-normal units for every E2 cell; "
            f"× POR_STDEV² ({k['POR_STDEV']:g}²) = {sill_phys:g} porosity %².",
            f"porosity-unit realization variance (ddof=0) / {sill_phys:g}: min {df['ratio_phys'].min():.12f}, max "
            f"{df['ratio_phys'].max():.12f} (GSLIB.affine rescales every map to stdev {k['POR_STDEV']:g} with "
            "np.std, ddof=0). This is why panels A and B use the pre-rescaling standard-normal field.",
            f"variogram: {k['N_PAIRS_DRAWN']:,} random cell pairs, RandomState({k['VARIOGRAM_PAIR_SEED']}), identical "
            f"pair draw for every map, {bw:g} m bins to {P1_LAG_MAX_M:g} m, full 50x50 grid; reported bins all have "
            f">= {k['MIN_PAIRS_PER_BIN']} pairs (min pairs at range − {bw / 2:g} m: {int(df['np_lo'].min())}).",
            f"'lag nearest the true range': every true range is a multiple of {bw:g} m and hence a bin EDGE; the two "
            f"adjacent bins are equidistant. Panel C uses the lower bin (range − {bw / 2:g} m, same rule as F3c); "
            "the upper bin is in panel line C above and per cell below.",
            "model curve = spherical_semivariance (nugget NUG x POR_STDEV², structured CC1 x POR_STDEV², range = "
            "true range); E2 nugget asserted == NUG for every cell.",
            f"panel A/C horizontal spread is cosmetic (+-{P1_JITTER_FRAC:g} x level spacing, ordered by truth seed).",
            f"E2: 1 sample set per truth, n = {sorted(df['n'].unique())} samples.",
            "per cell:",
            *per_cell,
        ],
    )
    return {"note": note, "status_lines": lines, "bw": bw,
            "df": df[["range_m", "truth_seed", "ratio_ns", "umg_kriging", "gam_ratio_lo"]]}


def draw_p1(d):
    note, df, bw = d["note"], d["df"], d["bw"]
    levels = sorted(df["range_m"].unique())
    step = float(np.min(np.diff(levels)))
    colors = _level_colors(levels)
    fig, rect = _new_figure(plot_height_mm=46.0, status_text=note, top_mm=16.0, left_mm=13.0, right_mm=3.0)
    gs = fig.add_gridspec(1, 3, left=rect[0], bottom=rect[1], right=rect[2], top=rect[3], wspace=0.42)
    axA, axB, axC = (fig.add_subplot(gs[0, i]) for i in range(3))

    def level_scatter(ax, col):
        for lvl in levels:
            sub = df[df["range_m"] == lvl].sort_values("truth_seed")
            x = lvl + _jitter(len(sub), step, P1_JITTER_FRAC)
            ax.scatter(x, sub[col], s=P1_MARKER_S, color=colors[lvl], edgecolors="none", alpha=0.85, zorder=3)
            ax.plot([lvl - 0.3 * step, lvl + 0.3 * step], [sub[col].mean()] * 2, color="black", linewidth=1.0,
                    zorder=4)
        ax.axhline(1.0, color="0.5", linestyle="--", linewidth=0.5, zorder=1)
        ax.set_xticks(levels)
        ax.set_xticklabels([f"{v:g}" for v in levels])
        ax.set_xlabel("True range (m)")
        ax.grid(True, axis="y")

    level_scatter(axA, "ratio_ns")
    axA.set_ylabel("Realization variance / model sill\n(standard-normal field, before rescaling)")
    for lvl in levels:
        axB.scatter(df.loc[df["range_m"] == lvl, "ratio_ns"], df.loc[df["range_m"] == lvl, "umg_kriging"],
                    s=P1_MARKER_S + 2, marker=METHOD_MARKERS["kriging"], color=colors[lvl], edgecolors="none",
                    alpha=0.9, zorder=3, label=f"{lvl:g} m")
    axB.set_xlabel("Realization variance / model sill\n(standard-normal field, before rescaling)")
    axB.set_ylabel(f"{METHOD_LABELS['kriging']} {UMG_LABEL}")
    axB.grid(True)
    h, l = axB.get_legend_handles_labels()
    fig.legend(h, l, loc="upper center", bbox_to_anchor=(0.5, 1.0),
               ncol=len(levels), borderaxespad=0.3, handletextpad=0.1, columnspacing=1.0,
               title="True range (B; colours also in A, C)", title_fontsize=FONT_PT)
    level_scatter(axC, "gam_ratio_lo")
    axC.set_ylabel("Experimental / model semivariance\nat lag = range − %g m" % (bw / 2))
    for ax, letter in zip((axA, axB, axC), "ABC"):
        _panel_label(ax, letter, dx_pt=-30.0)
    return fig


