# level colours for range / density levels (not methods): sequential colormap sampled evenly
LEVEL_CMAP = "viridis"
LEVEL_CMAP_SPAN = (0.0, 0.9)   # avoid the near-white yellow end


def _level_colors(levels):
    cmap = matplotlib.colormaps[LEVEL_CMAP]
    t = np.linspace(*LEVEL_CMAP_SPAN, len(levels))
    return {lvl: cmap(v) for lvl, v in zip(levels, t)}


def _status(stem, **kw):
    lines = sb._status_file(stem, **kw)
    lines[1] = f"generated by: {THIS_SCRIPT} (called from results/processed/paper_storyboard/make_storyboard_figures.py)"
    return lines


def _per_cell(metrics, exp, method, metric):
    s = metrics[(metrics["experiment"] == exp) & (metrics["method"] == method) & (metrics["metric"] == metric)]
    key = ["axis_level", "truth_seed", "sample_rep"]
    if s.duplicated(key).any():
        raise ValueError(f"{exp} {method} {metric}: duplicate cells")
    return s.set_index(key)["value"]


