def _node_order(summ, m):
    """Node order of metrics_summary.csv for method m (make_f7_tables.py breaks ties by this order)."""
    g = summ[(summ["method"] == m) & (summ["metric"] == "mse")]
    return list(zip(g["grid_i"], g["grid_j"]))


def _best(g, metric, order):
    rank = {n: i for i, n in enumerate(order)}
    g = g.assign(_o=[rank[(i, j)] for i, j in zip(g["grid_i"], g["grid_j"])]).sort_values("_o")
    g = g.sort_values("value", ascending=(metric == "mse"), kind="mergesort")
    best = g.iloc[0]
    n_tie = int((g["value"] == best["value"]).sum())
    return best, n_tie


def _ring_offsets(ax, xs, ys, ylog):
    """Deterministic jitter: markers sharing a plotted position are spread HORIZONTALLY only, centred on
    the node, P7_JITTER_DX axes-fraction apart (y stays exact, so a marker never drifts toward a
    neighbouring second-hyperparameter node). Returns jittered (x, y) and the number of shared positions."""
    return _ring_offsets_lims(ax.get_xlim(), ax.get_ylim(), xs, ys, ylog)


def _ring_offsets_lims(xlim, ylim, xs, ys, ylog):
    """_ring_offsets for given axis limits (the compute step uses it with the limits draw_p7 sets)."""
    x0, x1 = xlim
    y0, y1 = ylim
    u = (np.log10(xs) - np.log10(x0)) / (np.log10(x1) - np.log10(x0))
    yy = np.log10(ys) if ylog else np.asarray(ys, float)
    ly0, ly1 = (np.log10(y0), np.log10(y1)) if ylog else (y0, y1)
    v = (yy - ly0) / (ly1 - ly0)
    out_u, out_v = u.copy(), v.copy()
    keys = [(round(a, 9), round(b, 9)) for a, b in zip(u, v)]
    groups = {}
    for idx, kk in enumerate(keys):
        groups.setdefault(kk, []).append(idx)
    n_shared = 0
    for idxs in groups.values():
        if len(idxs) < 2:
            continue
        n_shared += 1
        offs = (np.arange(len(idxs)) - (len(idxs) - 1) / 2.0) * P7_JITTER_DX
        for o, idx in zip(offs, idxs):
            out_u[idx] += o
    xj = 10 ** (np.log10(x0) + out_u * (np.log10(x1) - np.log10(x0)))
    yj_l = ly0 + out_v * (ly1 - ly0)
    yj = 10 ** yj_l if ylog else yj_l
    return xj, yj, n_shared


