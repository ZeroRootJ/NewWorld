        f"sample set. y = UMG(GP-MLE) − UMG(SGS). A: x = |ln(GP practical range / true range {true_r:g} m)|, practical "
        f"range = {fac:.4f} × fitted length scale. B: x = fitted GP noise variance as a fraction of the sample variance "
