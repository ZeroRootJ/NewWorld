def _p4_table(mt):
    ed = mt["exp"]["density"]
    met = read_metrics_csv(MTA_METRICS)
    hyper = pd.read_csv(MTA_HYPER, dtype={"axis_level": str})
    h = hyper[(hyper["experiment"] == ed["experiment"]) & (hyper["method"] == "gp_mle")]
    key = ["axis_level", "truth_seed", "sample_rep"]
    hw = h.pivot_table(index=key, columns="parameter", values="value", aggfunc="first")
    if h.duplicated(key + ["parameter"]).any():
        raise ValueError("P4: duplicate GP hyperparameter rows")
    df = hw[["gp_practical_range_m", "gp_noise_variance_normalized", "gp_length_scale_m"]].copy()
    for m in ("gp_mle", "sgs", "kriging"):
        df[f"umg_{m}"] = _per_cell(met, ed["experiment"], m, "umg")
    if df.isna().any().any() or len(df) != ed["n_cells"] * ed["n_levels"]:
        raise ValueError(f"P4: incomplete join ({len(df)} rows)")
    from src.experiments.qc_nugget_axis import GP_PRACTICAL_RANGE_FACTOR
    if not np.allclose(df["gp_practical_range_m"], GP_PRACTICAL_RANGE_FACTOR * df["gp_length_scale_m"], rtol=1e-12):
        raise ValueError("P4: practical range != factor x length scale")
    true_r = mt["dens"]["truth_range_m"]
    df["abs_log_range_err"] = np.abs(np.log(df["gp_practical_range_m"] / true_r))
    df["d_sgs"] = df["umg_gp_mle"] - df["umg_sgs"]
    df["d_kriging"] = df["umg_gp_mle"] - df["umg_kriging"]
    # GP noise lower bound from the run manifests (kernel_init.noise_level_bounds), one per cell
    cells = ed["cells"].set_index(key)
    lb = set()
    for rd in cells["run_dir_gp_mle_b"]:
        p = json.loads((_REPO_ROOT / rd / "manifest.json").read_text(encoding="utf-8"))["params"]
        if not p.get("normalize_y"):
            raise ValueError(f"P4: {rd} normalize_y is not True")
        lb.add(float(p["kernel_init"]["noise_level_bounds"][0]))
    if len(lb) != 1:
        raise ValueError(f"P4: GP noise lower bounds differ across cells {lb}")
    df.attrs["noise_lower_bound"] = lb.pop()
    out = df.reset_index()
    out.attrs = df.attrs
    return out, true_r, GP_PRACTICAL_RANGE_FACTOR


def compute_p4(mt):
    from scipy.stats import spearmanr
    stem = "P4_gp_param_error_vs_umg_loss"
    ed = mt["exp"]["density"]
    dens = mt["dens"]
    df, true_r, fac = _p4_table(mt)
    true_nug = ed["nug"]
